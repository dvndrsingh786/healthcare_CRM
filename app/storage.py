# ---------- Signed tokens ----------

def _b64(data):
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def _unb64(text):
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def _signature(body):
    return _b64(hmac.new(get_settings().secret_key.encode(), body.encode(), hashlib.sha256).digest())


def sign(action, document_id, user_id, scope, seconds=None):
    """Returns (token, expires_at_unix)."""
    expires = int(time.time()) + (seconds or get_settings().signed_url_seconds)
    body = _b64(json.dumps({"a": action, "d": str(document_id), "u": str(user_id), "s": scope, "e": expires,
                            "n": secrets.token_hex(4)}, separators=(",", ":")).encode())
    return f"{body}.{_signature(body)}", expires


def verify(token, action):
    """The payload of a valid, unexpired token for `action`, or a 403 with one generic message."""
    denied = ApiError(403, "INVALID_LINK", "This link is invalid or has expired. Request a new one.")
    try:
        body, signature = token.split(".", 1)
        if not hmac.compare_digest(signature, _signature(body)):
            raise denied
        payload = json.loads(_unb64(body))
    except (ValueError, TypeError) as error:
        raise denied from error
    if payload.get("a") != action or payload.get("e", 0) < time.time():
        raise denied
    return payload
